#!/usr/bin/env bash
# Installs the QA agents and skills for Claude Code or GitHub Copilot.
#   ./install.sh                             Claude Code (and VS Code Copilot): link into ~/.claude
#   ./install.sh --copilot                   GitHub Copilot without Claude Code (VS Code, IntelliJ): install into ~/.copilot
#   ./install.sh --settings                  add this repo's deny rules to ~/.claude/settings.json (Claude Code)
#   ./install.sh --project <path> [--update] copy the agents and skills into <path>/.claude for a team
#   ./install.sh [--copilot] --uninstall     remove what the install added and restore what it replaced
# It never touches ~/.claude/CLAUDE.md. ~/.claude/settings.json changes only with --settings, which adds missing deny
# rules after a backup. --project copies settings.example.json (allow and deny lists) into a team repo that has no
# .claude/settings.json; for an existing one it adds only the missing deny rules, with --update and after a backup.
# Anything a link install replaces is moved to <target>/backups/qa-<timestamp>-NNN/ first. --project --update
# overwrites the copied agents and skills in place (the team repo's git history is their backup).
set -euo pipefail

# Resolve the script's real location, so running it through a symlink still finds the repo.
SELF="${BASH_SOURCE[0]}"
while [[ -L "$SELF" ]]; do
  target="$(readlink "$SELF")"
  [[ "$target" == /* ]] || target="$(dirname "$SELF")/$target"
  SELF="$target"
done
REPO="$(cd "$(dirname "$SELF")" && pwd)"
CLAUDE_HOME="${CLAUDE_HOME:-$HOME/.claude}"
# Folder the current mode installs into: CLAUDE_HOME by default, COPILOT_HOME with --copilot.
TARGET_HOME="$CLAUDE_HOME"
COPILOT_HOME="${COPILOT_HOME:-$HOME/.copilot}"
# First line of every agent file generated for Copilot; marks the files this script owns.
COPILOT_MARKER="<!-- Generated by claude-qa-automation/install.sh --copilot from agents/"
BACKUP_DIR=""

# The comment block at the top of this file, up to "set -euo pipefail", without the leading "# ".
header_text() { sed -n '2,/^set -euo pipefail/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; }

usage() {
  local code="${1:-0}"
  if [[ "$code" -eq 0 ]]; then
    header_text
  else
    header_text >&2
  fi
  exit "$code"
}

die() {
  echo "error: $*" >&2
  usage 1
}

# Sets this run's backup folder on first use: qa-<stamp>-NNN, the first free NNN, so backups never
# overwrite each other and sort oldest to newest. BACKUP_STAMP exists so tests can force a collision.
init_backup_dir() {
  [[ -z "$BACKUP_DIR" ]] || return 0
  local base i=0
  base="$TARGET_HOME/backups/qa-${BACKUP_STAMP:-$(date +%Y%m%d-%H%M%S)}"
  while :; do
    BACKUP_DIR="$(printf '%s-%03d' "$base" "$i")"
    [[ -e "$BACKUP_DIR" ]] || return 0
    i=$((i + 1))
    if [[ $i -gt 999 ]]; then
      echo "error: more than 1000 backups for one second in $TARGET_HOME/backups" >&2
      BACKUP_DIR=""
      return 1
    fi
  done
}

# True for a broken link that points at <something>/<dir>/<name> where <dir>/<name> matches the link's own
# location, i.e. a link left behind by an earlier install from a clone that has since moved.
is_stale_link() {
  local dest="$1" target
  [[ -L "$dest" && ! -e "$dest" ]] || return 1
  target="$(readlink "$dest")"
  [[ "$(basename "$target")" == "$(basename "$dest")" ]] || return 1
  [[ "$(basename "$(dirname "$target")")" == "$(basename "$(dirname "$dest")")" ]]
}

# Links $TARGET_HOME/<rel> to $REPO/<rel>. Whatever was there (a file, a folder, a link from another repo or a
# broken link) is moved to the backup folder first, so --uninstall can put it back.
link_one() {
  local rel="$1" src="$REPO/$1" dest="$TARGET_HOME/$1" note=""
  if [[ -L "$dest" && "$(readlink "$dest")" == "$src" ]]; then
    echo "  ok        $rel"
    return
  fi
  if [[ -e "$dest" || -L "$dest" ]]; then
    if is_stale_link "$dest"; then
      note=" (was a broken link)"
    elif [[ -L "$dest" ]]; then
      note=" (was a link to $(readlink "$dest"))"
    fi
    init_backup_dir
    mkdir -p "$BACKUP_DIR/$(dirname "$rel")"
    mv "$dest" "$BACKUP_DIR/$rel"
    echo "  backed up $rel$note"
  else
    echo "  linked    $rel"
  fi
  mkdir -p "$(dirname "$dest")"
  ln -s "$src" "$dest"
}

# Refuses to install into an agents or skills folder under <base> that is itself a link, because the entries
# would land inside whatever that folder points to.
check_target_dirs() {
  local base="$1" d
  for d in agents skills; do
    if [[ -L "$base/$d" ]]; then
      echo "error: $base/$d is a link to $(readlink "$base/$d"); installing would write into it." >&2
      echo "       Replace it with a real folder first." >&2
      exit 1
    fi
  done
}

# Prints every path the user install links, relative to the repo.
user_entries() {
  local f
  for f in "$REPO"/agents/*.md "$REPO"/skills/*/; do
    [[ -e "$f" ]] || continue
    f="${f%/}"
    echo "${f#"$REPO"/}"
  done
}

kind() { if [[ -d "$1" ]]; then echo dir; else echo file; fi; }

copy_one() {
  local src="$1" dest="$2" update="$3"
  if [[ -L "$dest" ]]; then
    echo "  SKIP      $dest (is a symlink - remove it to install a copy)"
  elif [[ -e "$dest" && "$(kind "$src")" != "$(kind "$dest")" ]]; then
    echo "  SKIP      $dest (exists as a different type - remove it to install)"
  elif [[ ! -e "$dest" ]]; then
    cp -Rp "$src" "$dest"
    echo "  copied    $dest"
  elif diff -rq "$src" "$dest" >/dev/null 2>&1; then
    echo "  ok        $dest"
  elif [[ "$update" == yes ]]; then
    rm -rf "$dest"
    cp -Rp "$src" "$dest"
    echo "  updated   $dest (local edits and added files replaced)"
  else
    echo "  DIFFERS   $dest (--update replaces it, including local edits)"
  fi
}

# A team repo's .claude/settings.json: created from settings.example.json if absent. If it exists, it is checked for
# the deny rules from settings.example.json, and --update adds the missing ones (the file is rewritten as JSON, with the same values and indentation).
project_settings() {
  local target="$1" update="$2" missing errfile
  if [[ -L "$target" || ! -e "$target" ]]; then
    copy_if_absent "$REPO/settings.example.json" "$target" "merge settings.example.json by hand"
    return
  fi
  if ! have_python3; then
    echo "  SKIP      $target (exists; checking its deny rules needs python3 - compare with settings.example.json by hand)"
    return
  fi
  if ! errfile="$(mktemp)"; then
    echo "  SKIP      $target (exists; could not create a temp file to check its deny rules)"
    return
  fi
  if ! missing="$(settings_tool check "$target" 2>"$errfile")"; then
    echo "  SKIP      $target (exists; could not check its deny rules: $(tail -n 1 "$errfile"))"
    rm -f "$errfile"
    return
  fi
  rm -f "$errfile"
  if [[ -z "$missing" ]]; then
    echo "  ok        $target has every deny rule from settings.example.json"
  elif [[ "$update" == yes ]]; then
    if ! init_backup_dir; then
      echo "  FAILED    $target (no free backup folder, see the error above; the file is unchanged)"
      return
    fi
    if ! { mkdir -p "$BACKUP_DIR" && cp -p "$target" "$BACKUP_DIR/project-settings.json" && chmod go-w "$BACKUP_DIR/project-settings.json"; }; then
      echo "  FAILED    $target (could not back it up to $BACKUP_DIR, see the error above; the file is unchanged)"
      return
    fi
    if ! settings_tool merge "$target"; then
      echo "  FAILED    $target (could not add the deny rules; the file is unchanged)"
      return
    fi
    echo "  added     $(wc -l <<<"$missing" | tr -d ' ') deny rule(s) to $target (backup: $BACKUP_DIR/project-settings.json)"
  else
    echo "  MISSING   $target lacks $(wc -l <<<"$missing" | tr -d ' ') deny rule(s) from settings.example.json (--update adds them):"
    while IFS= read -r r; do echo "              $r"; done <<<"$missing"
  fi
}

copy_if_absent() {
  local src="$1" dest="$2" hint="$3"
  if [[ -L "$dest" ]]; then
    echo "  SKIP      $dest (is a symlink - remove it to install a copy)"
  elif [[ -e "$dest" ]]; then
    echo "  SKIP      $dest (exists - $hint)"
  else
    cp -p "$src" "$dest"
    echo "  copied    $dest"
  fi
}

# True if a usable python3 is available. On macOS without Command Line Tools, /usr/bin/python3 is a stub that
# opens an install dialog, so it is never run. The QA_* variables exist so tests can simulate that machine.
have_python3() {
  local py
  py="$(command -v python3 || true)"
  [[ -n "$py" ]] || return 1
  if [[ "$py" == "${QA_PY_STUB:-/usr/bin/python3}" && "${QA_OS:-$(uname -s)}" == Darwin ]] &&
    ! "${QA_XCODE_SELECT:-xcode-select}" -p >/dev/null 2>&1; then
    return 1
  fi
}

# settings_tool <check|merge> [file]: check prints the deny rules from settings.example.json that the file
# (~/.claude/settings.json by default) lacks, one per line; merge adds them. Both fail with a one-line reason if the
# file can't be read or has an unexpected shape, and merge writes atomically.
settings_tool() {
  python3 - "$1" "$REPO/settings.example.json" "${2:-$CLAUDE_HOME/settings.json}" <<'PY'
import json, os, re, stat, sys, tempfile
mode, example, target = sys.argv[1:4]

class DuplicateKey(ValueError):
    pass

def no_duplicate_keys(pairs):
    # json.loads keeps only the last of two equal keys; a merge would then silently drop the first one.
    keys = [k for k, _ in pairs]
    if len(keys) != len(set(keys)):
        raise DuplicateKey(next(k for k in keys if keys.count(k) > 1))
    return dict(pairs)

def fail(msg):
    print(msg, file=sys.stderr)
    sys.exit(2)

with open(example, encoding="utf-8") as f:
    want = json.load(f)["permissions"]["deny"]
data = {}
if os.path.exists(target):
    try:
        with open(target, encoding="utf-8") as f:
            raw = f.read()
        # An empty file is treated as an empty settings object.
        data = json.loads(raw, object_pairs_hook=no_duplicate_keys) if raw.strip() else {}
    except OSError as e:
        fail(f"could not read {target}: {e.strerror}")
    except DuplicateKey as e:
        fail(f"{target} has the same key twice in one object; merge it by hand")
    except UnicodeDecodeError as e:
        # Never echo the bytes: name only where the bad byte is.
        fail(f"{target} is not UTF-8 (byte offset {e.start})")
    except ValueError as e:
        fail(f"{target} is not valid JSON ({e})")
# Keep the file's own indentation (spaces or a tab), so a merge does not reformat a team's file. A file with no
# indented line (such as a one-line file) is written with 2 spaces.
indent = 2
if os.path.exists(target):
    m = re.search(r"\n([ \t]+)\S", raw)
    if m:
        indent = m.group(1)
if not isinstance(data, dict):
    fail(f"{target} has an unexpected shape: the top level is not an object")
perms = data.get("permissions")
if perms is None:
    perms = {}
if not isinstance(perms, dict):
    fail(f"{target} has an unexpected shape at permissions")
deny = perms.get("deny")
if deny is None:
    deny = []
if not isinstance(deny, list):
    fail(f"{target} has an unexpected shape at permissions.deny")
missing = [r for r in want if r not in deny]
if mode == "check":
    print("\n".join(missing))
    sys.exit(0)
data["permissions"] = perms
perms["deny"] = deny + missing
folder = os.path.dirname(target) or "."
try:
    fd, tmp = tempfile.mkstemp(dir=folder, prefix=".settings.", suffix=".json")
except OSError as e:
    fail(f"could not write next to {target}: {e.strerror}")
try:
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        # mkstemp creates the file as 0600; keep the existing file's permissions (or the usual 0644 for a new one).
        os.chmod(tmp, stat.S_IMODE(os.stat(target).st_mode) if os.path.exists(target) else 0o644)
        # allow_nan=False: a number too big for a float (1e400) would otherwise come back as Infinity, which is not JSON.
        json.dump(data, f, indent=indent, ensure_ascii=False, allow_nan=False)
        f.write("\n")
    # Test-only fault injection (like the QA_* hooks above): simulates a failure after the temp file exists.
    if os.environ.get("QA_FAIL_SETTINGS_WRITE"):
        raise OSError(5, "simulated write failure")
    os.replace(tmp, target)
except BaseException as e:
    # Never leave a half-written temp file behind, where it could end up committed in a team repo.
    if os.path.exists(tmp):
        os.unlink(tmp)
    if isinstance(e, OSError):
        fail(f"could not write {target}: {e.strerror}")
    if isinstance(e, ValueError):
        # Name the error type only: the message of an encoding error quotes the offending text.
        fail(f"could not write {target}: a value cannot be written back as JSON ({type(e).__name__})")
    raise
PY
}

# Adds the missing deny rules to ~/.claude/settings.json (backed up first). Refuses to write through a link,
# because then the file belongs to another repo and the rules belong there.
merge_settings() {
  local target="$CLAUDE_HOME/settings.json" missing
  if ! have_python3; then
    echo "error: --settings needs a working python3" >&2
    return 1
  fi
  if [[ -e "$target" ]] && python3 -c 'import os,stat,sys; sys.exit(0 if os.stat(sys.argv[1]).st_mode & 0o022 else 1)' "$target"; then
    echo "  WARNING   settings.json is writable by other users or your group; consider: chmod go-w $target"
  fi
  if ! missing="$(settings_tool check)"; then
    echo "error: settings.json was left unchanged" >&2
    return 1
  fi
  if [[ -z "$missing" ]]; then
    echo "  ok        settings.json already has every deny rule from settings.example.json"
    return
  fi
  if [[ -L "$target" ]]; then
    echo "  SKIP      settings.json is a link to $(readlink "$target")"
    echo "            Add these deny rules in that repo instead:"
    while IFS= read -r r; do echo "              $r"; done <<<"$missing"
    return 1
  fi
  mkdir -p "$CLAUDE_HOME"
  if [[ -e "$target" ]]; then
    if ! init_backup_dir; then
      echo "error: no free backup folder; settings.json was left unchanged" >&2
      return 1
    fi
    # -p copies the original's exact mode bits; plain cp would strip bits the umask removes.
    # go-w then keeps others from editing the backup even when the original is writable by them.
    if ! { mkdir -p "$BACKUP_DIR" && cp -p "$target" "$BACKUP_DIR/settings.json" && chmod go-w "$BACKUP_DIR/settings.json"; }; then
      echo "error: could not back up settings.json to $BACKUP_DIR, see the error above; the file is unchanged" >&2
      return 1
    fi
    echo "  backed up settings.json"
  fi
  if ! settings_tool merge; then
    echo "error: could not add the deny rules; settings.json was left unchanged" >&2
    return 1
  fi
  echo "  added     $(wc -l <<<"$missing" | tr -d ' ') deny rule(s) to settings.json"
}

# Reports optional tools the agents use. Never fails the install.
check_dependencies() {
  local cmd purpose
  echo
  echo "Dependency check:"
  while IFS='|' read -r cmd purpose; do
    if command -v "$cmd" >/dev/null 2>&1; then
      echo "  found     $cmd"
    else
      echo "  missing   $cmd ($purpose)"
    fi
  done <<'DEPS'
claude|Claude Code - not needed if you use GitHub Copilot (./install.sh --copilot)
git|diffs, PR reviews
python3|settings check and Excel requirements in /test-developer
gh|GitHub PRs, issues and Actions runs
glab|GitLab MRs, issues and pipelines
az|Azure DevOps work items, PRs and pipelines - or use the Azure DevOps MCP server
jira|Jira Data Center issues (jira-cli) - Jira Cloud uses the Atlassian MCP server instead
DEPS
  if command -v python3 >/dev/null 2>&1 && ! have_python3; then
    echo "  missing   python3 (only the macOS stub is installed: xcode-select --install or brew install python)"
  elif have_python3 && ! python3 -c "import openpyxl" >/dev/null 2>&1; then
    echo "  missing   openpyxl (Excel requirements in /test-developer: pip3 install --user openpyxl)"
  fi
  # Checks the extension folder instead of running az, which can be slow to start.
  local azext="${AZURE_EXTENSION_DIR:-$HOME/.azure/cliextensions}/azure-devops"
  if command -v az >/dev/null 2>&1 && [[ -z "$(ls -A "$azext" 2>/dev/null)" ]]; then
    echo "  missing   az azure-devops extension (az extension add --name azure-devops)"
  fi
}

# Prints the newest backup of <rel>, if any. Folder names sort by time under byte order (LC_ALL=C).
latest_backup() {
  local b found
  found="$(for b in "$TARGET_HOME"/backups/qa-*/"$1"; do
    if [[ -e "$b" || -L "$b" ]]; then printf '%s\n' "$b"; fi
  done | LC_ALL=C sort | tail -n 1)"
  [[ -n "$found" ]] && echo "$found"
}

# Removes our links and puts back the newest backup of each, so the machine returns to its state before install.
remove_links() {
  local n=0 link target rel backup
  while IFS= read -r rel; do
    link="$TARGET_HOME/$rel"
    [[ -L "$link" ]] || continue
    target="$(readlink "$link")"
    if [[ "$target" == "$REPO/"* ]] || is_stale_link "$link"; then
      rm "$link"
      n=$((n + 1))
      if backup="$(latest_backup "$rel")"; then
        mv "$backup" "$link"
        echo "  restored  $rel (from ${backup#"$TARGET_HOME"/})"
      else
        echo "  removed   $rel"
      fi
    fi
  done < <(user_entries)
  echo "Removed $n link(s)."
}

uninstall() {
  remove_links
  echo "settings.json is left as is; older backups stay in $TARGET_HOME/backups/."
}

# Copilot's tools allowlist for the generated agents. Copilot's .agent.md format has no disallowedTools, so instead
# of blocking edits the list leaves out the edit tool. `execute` still runs shell commands, and an MCP wildcard
# grants all of that server's tools, so read-only stays a rule in the instructions, as in the Claude version.
COPILOT_TOOLS=""

# Builds COPILOT_TOOLS, adding '<server>/*' for each name in COPILOT_MCP_SERVERS. Splits on spaces without glob
# expansion and validates every name before anything is written.
init_copilot_tools() {
  local server servers=()
  COPILOT_TOOLS="'read', 'search', 'execute', 'web', 'todo'"
  IFS=' ' read -r -a servers <<<"${COPILOT_MCP_SERVERS:-}"
  for server in ${servers[@]+"${servers[@]}"}; do
    # Real names can look like mcp.dev.azure.com/sc-ado; quotes, globs and other shell or YAML specials are rejected.
    [[ "$server" =~ ^[A-Za-z0-9._@:/-]+$ ]] || die "COPILOT_MCP_SERVERS: invalid server name '$server'"
    COPILOT_TOOLS="$COPILOT_TOOLS, '$server/*'"
  done
}

# Prints the Copilot version of an agent: name and description (with any indented continuation lines) are kept,
# the tools allowlist replaces disallowedTools/tools, model and color are dropped, and the body is unchanged.
# Every agent gets the read-only allowlist, except one whose frontmatter has the comment line
# "# copilot: orchestrator" (qa-lead): it gets no tools list, which Copilot treats as every tool (including the
# agent tool and all MCP servers), and an agents list naming every other agent, so it can delegate to the
# specialists. A YAML comment, so Claude Code ignores it.
# Windows line endings are removed. Fails if the file has no closed frontmatter or lacks name or description.
copilot_agent() {
  local src="$1" others="" f
  for f in "$REPO"/agents/*.md; do
    [[ "$(basename "$f" .md)" == "$(basename "$src" .md)" ]] && continue
    others="${others:+$others, }'$(basename "$f" .md)'"
  done
  awk -v marker="$COPILOT_MARKER$(basename "$src") -->" -v tools="$COPILOT_TOOLS" -v others="$others" '
    { sub(/\r$/, "") }
    NR == 1 { if ($0 != "---") exit 2; print; fm = 1; next }
    fm && $0 == "---" {
      if (!orchestrator) {
        print "tools: [" tools "]"
      } else {
        # No tools list: the lead is the main conversation, like the default Agent mode, and gets every tool,
        # including all MCP servers.
        print "agents: [" others "]"
      }
      print "---"
      print ""
      print marker
      fm = 0; body = 1; closed = 1; next
    }
    fm && $0 == "# copilot: orchestrator" { orchestrator = 1; next }
    fm && /^(name|description):/ { keep = 1; if ($0 ~ /^name:/) has_name = 1; else has_desc = 1; print; next }
    fm && /^[ \t]/ && keep { print; next }
    fm { keep = 0; next }
    body { print }
    END { if (!closed || !has_name || !has_desc) exit 2 }
  ' "$src"
}

# Writes the Copilot version of one agent to $TARGET_HOME/agents/<name>.agent.md. Files this script generated
# are replaced in place; anything else is backed up first.
write_copilot_agent() {
  local src="$1" name rel dest content
  name="$(basename "$src" .md)"
  rel="agents/$name.agent.md"
  dest="$TARGET_HOME/$rel"
  content="$(copilot_agent "$src")"
  if [[ -f "$dest" && ! -L "$dest" ]] && head -n 20 "$dest" | grep -qF "$COPILOT_MARKER"; then
    if [[ "$(cat "$dest")" == "$content" ]]; then
      echo "  ok        $rel"
      return
    fi
    echo "  updated   $rel (replaced the previous generated version, including any local edits)"
  elif [[ -e "$dest" || -L "$dest" ]]; then
    init_backup_dir
    mkdir -p "$BACKUP_DIR/agents"
    mv "$dest" "$BACKUP_DIR/$rel"
    echo "  backed up $rel"
  else
    echo "  generated $rel"
  fi
  mkdir -p "$TARGET_HOME/agents"
  printf '%s\n' "$content" >"$dest"
}

# Prints the agent files this script generated in the Copilot folder, one per line.
generated_copilot_agents() {
  local f
  for f in "$TARGET_HOME"/agents/*.agent.md; do
    if [[ -f "$f" && ! -L "$f" ]] && head -n 20 "$f" | grep -qF "$COPILOT_MARKER"; then
      echo "$f"
    fi
  done
}

# Removes broken skill links into this repo (skills that left it), backing each one up first.
prune_dead_skill_links() {
  local link rel
  for link in "$TARGET_HOME"/skills/*; do
    [[ -L "$link" && ! -e "$link" ]] || continue
    # Ours if it points into this repo, or into a moved clone (same skills/<name> path), for a skill we no longer ship.
    if [[ "$(readlink "$link")" == "$REPO/"* ]] || { is_stale_link "$link" && [[ ! -d "$REPO/skills/$(basename "$link")" ]]; }; then
      rel="skills/$(basename "$link")"
      init_backup_dir
      mkdir -p "$BACKUP_DIR/skills"
      mv "$link" "$BACKUP_DIR/$rel"
      echo "  removed   $rel (no longer in this repo; link backed up)"
    fi
  done
}

install_copilot() {
  local d f
  init_copilot_tools
  # Convert every agent before writing anything, so a broken source leaves the install untouched.
  for f in "$REPO"/agents/*.md; do
    if ! copilot_agent "$f" >/dev/null; then
      echo "error: cannot convert $f: it needs a frontmatter block with name and description. Nothing was installed." >&2
      exit 1
    fi
  done
  echo "Installing QA agents and skills for GitHub Copilot into $TARGET_HOME"
  check_target_dirs "$TARGET_HOME"
  mkdir -p "$TARGET_HOME"
  for d in "$REPO"/skills/*/; do
    d="${d%/}"
    link_one "skills/$(basename "$d")"
  done
  prune_dead_skill_links
  for f in "$REPO"/agents/*.md; do
    write_copilot_agent "$f"
  done
  # Generated agents whose source left this repo.
  while IFS= read -r f; do
    [[ -n "$f" ]] || continue
    if [[ ! -f "$REPO/agents/$(basename "$f" .agent.md).md" ]]; then
      rm "$f"
      echo "  removed   agents/$(basename "$f") (no longer in this repo)"
    fi
  done < <(generated_copilot_agents)
  [[ -z "$BACKUP_DIR" ]] || echo "Replaced entries were moved to $BACKUP_DIR."
  check_dependencies
  echo
  if [[ -z "${COPILOT_MCP_SERVERS:-}" ]]; then
    echo
    echo "MCP: qa-lead can use all your Copilot MCP servers. The specialist agents can use only the servers you name:"
    echo "  COPILOT_MCP_SERVERS=\"mcp.dev.azure.com/sc-ado\" ./install.sh --copilot   (names as shown by MCP: List Servers)"
  fi
  echo
  echo "Done. Agents are generated copies: after git pull, run ./install.sh --copilot again to update them."
  echo
  echo "VS Code:  no setting needed. In Copilot Chat, pick an agent in the Agent dropdown; type / to run a skill"
  echo "          (/skills opens the Configure Skills menu). If one is missing: right-click in the Chat view > Diagnostics"
  echo "          lists every loaded agent and skill with any errors."
  echo "IntelliJ: turn on Settings > GitHub Copilot > Chat > Agent (on Copilot Business or Enterprise an admin must also"
  echo "          enable the Editor preview features policy). In Copilot Chat, pick an agent in the agent dropdown; type /"
  echo "          to run a skill."
}

uninstall_copilot() {
  local n=0 f rel backup
  while IFS= read -r f; do
    [[ -n "$f" ]] || continue
    rel="agents/$(basename "$f")"
    rm "$f"
    n=$((n + 1))
    if backup="$(latest_backup "$rel")"; then
      mv "$backup" "$f"
      echo "  restored  $rel (from ${backup#"$TARGET_HOME"/})"
    else
      echo "  removed   $rel"
    fi
  done < <(generated_copilot_agents)
  remove_links
  echo "Removed $n generated agent(s). Older backups stay in $TARGET_HOME/backups/."
}

if [[ "${1:-}" == --copilot ]]; then
  TARGET_HOME="$COPILOT_HOME"
  shift
  case "${1:-}" in
    "")
      [[ $# -eq 0 ]] || die "unexpected arguments"
      install_copilot
      ;;
    --uninstall)
      [[ $# -eq 1 ]] || die "--copilot --uninstall takes no more arguments"
      uninstall_copilot
      ;;
    -h|--help) usage 0 ;;
    *) die "--copilot combines only with --uninstall" ;;
  esac
  exit 0
fi

case "${1:-}" in
  "")
    [[ $# -eq 0 ]] || die "unexpected arguments"
